import { QUESTION_TYPES } from "@/lib/interview-prompt";

const esc = (value) =>
  String(value ?? "")
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");

export const verdict = (overall) =>
  overall >= 70 ? "Interview ready" : overall >= 45 ? "Getting there" : "Needs practice";

/** A file name for the report that is safe on any system. */
export function reportFileName(result) {
  const role = String(result.role ?? "interview")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");
  const day = (result.takenAt ?? new Date().toISOString()).slice(0, 10);
  return `slqg-mock-interview-${role || "report"}-${day}.html`;
}

/**
 * A complete, self-contained web page of an interview result: the score, strengths, what to work
 * on, the score by question type and every question with the answer given, the feedback and a model
 * answer. Everything from the student or the model is escaped. Opens in any browser, and
 * "Print" there saves it as a PDF.
 */
export function buildInterviewReportHtml(result, student = {}) {
  const date = new Date(result.takenAt ?? Date.now()).toLocaleDateString("en-IN", {
    day: "numeric",
    month: "long",
    year: "numeric",
  });
  const list = (items) =>
    items?.length
      ? `<ul>${items.map((i) => `<li>${esc(i)}</li>`).join("")}</ul>`
      : "<p>None noted.</p>";
  const byType = Object.entries(result.byType ?? {})
    .map(
      ([t, score]) =>
        `<tr><td>${esc(QUESTION_TYPES[t] ?? t)}</td><td class="bar"><i style="width:${Math.max(0, Math.min(100, score))}%"></i></td><td>${esc(score)}</td></tr>`,
    )
    .join("");
  const questions = (result.questions ?? [])
    .map(
      (q) => `<section class="q">
  <h3>Question ${q.index + 1} · ${esc(QUESTION_TYPES[q.type] ?? q.type)} <span>${esc(q.score)}/10</span></h3>
  <p class="question">${esc(q.question)}</p>
  <p><b>Your answer:</b> ${q.answer ? esc(q.answer) : "<i>Not answered</i>"}</p>
  ${q.code ? `<pre>${esc(q.code)}</pre>` : ""}
  <p><b>Feedback:</b> ${esc(q.feedback)}</p>
  ${q.better ? `<p><b>Model answer:</b></p><pre class="plain">${esc(q.better)}</pre>` : ""}
</section>`,
    )
    .join("\n");
  const integrity = result.violations
    ? `<p class="notice">${
        result.terminated
          ? `This interview was ended early: the student left the interview screen ${esc(result.violations)} times.`
          : `The student left the interview screen ${esc(result.violations)} time(s) during this interview.`
      }</p>`
    : "";
  return `<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<title>Mock interview report · ${esc(result.role)}</title>
<style>
  body{font:15px/1.55 system-ui,sans-serif;color:#0f172a;max-width:820px;margin:2rem auto;padding:0 1rem}
  h1{font-size:1.6rem;margin:0}h2{font-size:1.1rem;margin:1.6rem 0 .4rem;color:#00205f}
  .meta{color:#475569;margin:.2rem 0 1rem}.score{font-size:2.6rem;font-weight:800;color:#00205f}
  .pill{display:inline-block;padding:.15rem .7rem;border-radius:999px;background:#e6f1fa;color:#00205f;font-weight:600}
  .grid{display:grid;grid-template-columns:1fr 1fr;gap:1rem}table{width:100%;border-collapse:collapse}
  td{padding:.25rem .4rem}.bar{width:60%;background:#eef2f7}.bar i{display:block;height:.6rem;background:#0066cc}
  .q{border:1px solid #d9e1ec;border-radius:.6rem;padding:.8rem 1rem;margin:.8rem 0;break-inside:avoid}
  .q h3{margin:0 0 .3rem;font-size:1rem;display:flex;justify-content:space-between}.question{font-weight:600}
  pre{background:#0b1220;color:#e2e8f0;padding:.7rem;border-radius:.5rem;white-space:pre-wrap;word-break:break-word;font-size:.82rem}
  pre.plain{background:#f1f5f9;color:#0f172a}.notice{background:#e6f1fa;border-left:4px solid #00205f;padding:.6rem .8rem}
  footer{margin-top:2rem;color:#64748b;font-size:.8rem}
</style></head><body>
<h1>Mock interview report</h1>
<p class="meta">${esc(student.name ? `${student.name} · ` : "")}${esc(result.role)} · ${esc(date)}</p>
<p><span class="score">${esc(result.overall)}/100</span> <span class="pill">${esc(verdict(result.overall))}</span></p>
${integrity}
<p>${esc(result.summary)}</p>
<div class="grid"><div><h2>Strengths</h2>${list(result.strengths)}</div><div><h2>Work on</h2>${list(result.improvements)}</div></div>
<h2>Score by question type</h2><table>${byType}</table>
<h2>Questions and feedback</h2>
${questions}
<footer>Generated by SLQG · AI mock interview. Scores are practice feedback, not a hiring decision.</footer>
</body></html>`;
}
